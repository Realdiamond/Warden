// Embeds the built dashboard (web/dashboard/dist) into src/assets.ts so the Worker serves it
// directly — no separate asset upload. Assumes text assets (Vite inlines small images as data
// URIs, so the build is HTML/CSS/JS only). Run `pnpm --filter @monitor/dashboard build` first.
import { readFileSync, writeFileSync, readdirSync, statSync, existsSync } from "node:fs";
import { join, relative, extname } from "node:path";
import { fileURLToPath } from "node:url";

const here = fileURLToPath(new URL(".", import.meta.url));
const distDir = join(here, "..", "..", "..", "web", "dashboard", "dist");
const outFile = join(here, "..", "src", "assets.ts");

if (!existsSync(distDir)) {
  console.error(`Dashboard build not found at ${distDir}. Build it first.`);
  process.exit(1);
}

const TYPES = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json; charset=utf-8",
  ".svg": "image/svg+xml",
  ".ico": "image/x-icon",
  ".txt": "text/plain; charset=utf-8",
  ".webmanifest": "application/manifest+json",
};

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else out.push(p);
  }
  return out;
}

const files = walk(distDir);
let entries = "";
for (const f of files) {
  const rel = relative(distDir, f).split("\\").join("/");
  const type = TYPES[extname(rel)] ?? "application/octet-stream";
  const body = readFileSync(f, "utf8");
  entries += `  ${JSON.stringify(rel)}: { type: ${JSON.stringify(type)}, body: ${JSON.stringify(body)} },\n`;
}

const out =
  "// AUTO-GENERATED by scripts/bundle-dashboard.mjs — do not edit by hand.\n" +
  "export const ASSETS: Record<string, { type: string; body: string }> = {\n" +
  entries +
  "};\n";

writeFileSync(outFile, out);
console.log(`Wrote ${outFile} with ${files.length} file(s).`);
